#!/usr/bin/env node
// The sampler's samples into its source: reads samples.json and the WAVs it names (16-bit PCM,
// mono, in assets/) and writes the module's sample table, `assembly/samples.ts` in an
// AssemblyScript plugin (a folder with asconfig.json) or `src/samples.rs` in a Rust one (with
// Cargo.toml). An EST module imports nothing and reads no file at run time, so a sample travels
// inside module.wasm, as data. Run it after changing samples.json or a WAV:
//
//     node tools/embed-samples.mjs          # in the plugin's folder
//     node tools/embed-samples.mjs --check  # exit 1 when the source is not up to date
//
// The table: DATA, every sample's frames one after another (i16), and INFO, ten i32 a sample:
// offset into DATA, frames, the WAV's sample rate, root key, lowest key, highest key, lowest and
// highest velocity (in thousandths), loop start, loop end. Nothing but Node is needed.
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

/** The most frames all samples may total (about 2.6 MB of data: within memoryPagesMax). */
export const MAX_FRAMES = 1 << 20;

/** A 16-bit PCM mono WAV's rate and frames. */
export function readWav(bytes, name) {
  const v = new DataView(bytes.buffer, bytes.byteOffset, bytes.byteLength);
  const tag = (at) => String.fromCharCode(bytes[at], bytes[at + 1], bytes[at + 2], bytes[at + 3]);
  if (bytes.length < 12 || tag(0) !== 'RIFF' || tag(8) !== 'WAVE') throw new Error(`${name} is not a WAV file`);
  let fmt = null, data = null;
  for (let at = 12; at + 8 <= bytes.length;) {
    const id = tag(at), size = v.getUint32(at + 4, true);
    if (id === 'fmt ') fmt = { format: v.getUint16(at + 8, true), channels: v.getUint16(at + 10, true), rate: v.getUint32(at + 12, true), bits: v.getUint16(at + 22, true) };
    if (id === 'data') data = { at: at + 8, size: Math.min(size, bytes.length - at - 8) };
    at += 8 + size + (size & 1);
  }
  if (!fmt || !data) throw new Error(`${name} has no fmt or data chunk`);
  if (fmt.format !== 1 || fmt.bits !== 16 || fmt.channels !== 1) throw new Error(`${name} is not 16-bit PCM mono (export it as that)`);
  if (fmt.rate < 8000 || fmt.rate > 192000) throw new Error(`${name}: a sample rate of ${fmt.rate} Hz`);
  const frames = new Int16Array(data.size >> 1);
  for (let i = 0; i < frames.length; i++) frames[i] = v.getInt16(data.at + i * 2, true);
  return { rate: fmt.rate, frames };
}

const int = (x, lo, hi, what) => {
  if (!Number.isInteger(x) || x < lo || x > hi) throw new Error(`${what} is not a whole number from ${lo} to ${hi}`);
  return x;
};

/** The table for a plugin folder: { file, text } (nothing written). */
export function generated(dir) {
  const spec = JSON.parse(readFileSync(join(dir, 'samples.json'), 'utf8'));
  if (!Array.isArray(spec.samples) || spec.samples.length < 1 || spec.samples.length > 128) throw new Error('samples.json: "samples" is a list of 1 to 128 entries');
  const data = [], info = [];
  spec.samples.forEach((s, i) => {
    const what = `samples.json's entry ${i + 1}`;
    if (typeof s.file !== 'string' || !/^assets\/[A-Za-z0-9._-]+\.wav$/.test(s.file)) throw new Error(`${what}: "file" is a .wav in assets/`);
    const wav = readWav(new Uint8Array(readFileSync(join(dir, s.file))), s.file);
    const n = wav.frames.length;
    if (n < 2) throw new Error(`${s.file} has fewer than two frames`);
    const keys = s.keys ?? [0, 127], vel = s.velocity ?? [0, 1], loop = s.loop ?? [0, n];
    const lo = int(keys[0], 0, 127, `${what}'s lowest key`), hi = int(keys[1], lo, 127, `${what}'s highest key`);
    const vlo = Math.round(Number(vel[0]) * 1000), vhi = Math.round(Number(vel[1]) * 1000);
    int(vlo, 0, 1000, `${what}'s lowest velocity × 1000`); int(vhi, vlo, 1000, `${what}'s highest velocity × 1000`);
    const ls = int(loop[0], 0, n - 1, `${what}'s loop start`), le = int(loop[1], ls + 1, n, `${what}'s loop end`);
    info.push(data.length, n, wav.rate, int(s.root, 0, 127, `${what}'s root`), lo, hi, vlo, vhi, ls, le);
    for (const x of wav.frames) data.push(x);
  });
  if (data.length > MAX_FRAMES) throw new Error(`the samples total ${data.length} frames, more than ${MAX_FRAMES}`);
  const lines = (xs) => { const out = []; for (let i = 0; i < xs.length; i += 24) out.push(`  ${xs.slice(i, i + 24).join(', ')},`); return out.join('\n'); };
  const head = 'Generated by tools/embed-samples.mjs from samples.json and assets/: do not edit (run it again).';
  const count = spec.samples.length;
  if (existsSync(join(dir, 'Cargo.toml'))) {
    return {
      file: 'src/samples.rs',
      text: `//! ${head}\n\npub const COUNT: usize = ${count};\n/// Ten values a sample: offset, frames, rate, root, lowest key, highest key, lowest and highest velocity (thousandths), loop start, loop end.\npub const INFO_STRIDE: usize = 10;\npub static INFO: [i32; ${info.length}] = [\n${lines(info)}\n];\npub static DATA: [i16; ${data.length}] = [\n${lines(data)}\n];\n`,
    };
  }
  return {
    file: 'assembly/samples.ts',
    text: `// ${head}\n\nexport const COUNT: i32 = ${count};\n/** Ten values a sample: offset, frames, rate, root, lowest key, highest key, lowest and highest velocity (thousandths), loop start, loop end. */\nexport const INFO_STRIDE: i32 = 10;\nexport const INFO: usize = memory.data<i32>([\n${lines(info)}\n]);\nexport const DATA: usize = memory.data<i16>([\n${lines(data)}\n]);\n`,
  };
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const dir = resolve(dirname(fileURLToPath(import.meta.url)), '..');
  try {
    const { file, text } = generated(dir);
    const path = join(dir, file);
    const same = existsSync(path) && readFileSync(path, 'utf8') === text;
    if (process.argv.includes('--check')) {
      console.log(same ? `${file} is up to date` : `${file} is not up to date: run node tools/embed-samples.mjs`);
      process.exit(same ? 0 : 1);
    }
    if (!same) writeFileSync(path, text);
    console.log(`${file}: ${same ? 'up to date' : 'written'}`);
  } catch (err) {
    console.error(`embed-samples: ${err instanceof Error ? err.message : String(err)}`);
    process.exit(1);
  }
}
